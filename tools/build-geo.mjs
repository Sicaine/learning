//   node tools/build-geo.mjs            (downloads into .cache/geo on first run)
// Output is committed; rerun only when changing what the maps contain.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = process.env.GEO_CACHE || join(root, '.cache/geo');
const OUT = join(root, 'site/assets/data/geo');
const BASE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson';
mkdirSync(CACHE, { recursive: true }); mkdirSync(OUT, { recursive: true });

async function get(name) {
  const file = join(CACHE, `${name}.geojson`);
  if (!existsSync(file)) {
    console.log('downloading', name);
    const res = await fetch(`${BASE}/${name}.geojson`);
    if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
    writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return JSON.parse(readFileSync(file, 'utf8'));
}

// ---------- geometry helpers ----------
const CENTRAL = [-2, 43, 24, 58];       // Germany + neighbours, fine detail
const EUROPE = [-25, 14, 66, 72];       // Europe, Mediterranean, Near East, medium detail

function rdp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  const t2 = tol * tol;
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      let d2;
      if (len2 === 0) d2 = (px - ax) ** 2 + (py - ay) ** 2;
      else { const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len2)); d2 = (px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2; }
      if (d2 > max) { max = d2; idx = i; }
    }
    if (max > t2) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

function clipRing(ring, [x0, y0, x1, y1]) {
  // Sutherland–Hodgman against an axis-aligned rectangle.
  const edges = [
    [p => p[0] >= x0, (a, b) => [x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0])]],
    [p => p[0] <= x1, (a, b) => [x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0])]],
    [p => p[1] >= y0, (a, b) => [a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0]],
    [p => p[1] <= y1, (a, b) => [a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1]],
  ];
  let out = ring;
  for (const [inside, cross] of edges) {
    const inp = out; out = [];
    for (let i = 0; i < inp.length; i++) {
      const cur = inp[i], prev = inp[(i + inp.length - 1) % inp.length];
      if (inside(cur)) { if (!inside(prev)) out.push(cross(prev, cur)); out.push(cur); }
      else if (inside(prev)) out.push(cross(prev, cur));
    }
    if (!out.length) return [];
  }
  return out;
}

function clipLine(line, [x0, y0, x1, y1]) {
  // Split into runs of points inside the (slightly padded) box; good enough for rivers.
  const pad = 0.5, runs = []; let cur = [];
  for (const p of line) {
    if (p[0] >= x0 - pad && p[0] <= x1 + pad && p[1] >= y0 - pad && p[1] <= y1 + pad) cur.push(p);
    else { if (cur.length > 1) runs.push(cur); cur = []; }
  }
  if (cur.length > 1) runs.push(cur);
  return runs;
}

const r2 = n => Math.round(n * 100) / 100;
const flat = pts => { const o = []; let lx, ly; for (const [x, y] of pts) { const a = r2(x), b = r2(y); if (a === lx && b === ly) continue; o.push(a, b); lx = a; ly = b; } return o; };
const bboxHit = (pts, [x0, y0, x1, y1]) => pts.some(([x, y]) => x >= x0 && x <= x1 && y >= y0 && y <= y1);
const ringArea = r => { let s = 0; for (let i = 0; i < r.length; i++) { const [a, b] = r[i], [c, d] = r[(i + 1) % r.length]; s += a * d - c * b; } return Math.abs(s / 2); };

function polys(geom) { return geom.type === 'Polygon' ? [geom.coordinates] : geom.type === 'MultiPolygon' ? geom.coordinates : []; }

function buildPolys(geom, tol, clip, minArea) {
  const out = [];
  for (const poly of polys(geom)) {
    const rings = [];
    poly.forEach((ring, i) => {
      let r = clip ? clipRing(ring, clip) : ring;
      if (r.length < 4) return;
      r = rdp(r, tol);
      if (r.length < 4 || ringArea(r) < minArea) return;
      rings.push(flat(r));
    });
    if (rings.length && poly[0] && (!clip || bboxHit(poly[0], clip))) out.push(rings);
  }
  return out;
}

const write = (name, data) => {
  const body = `// Generated by tools/build-geo.mjs from Natural Earth (public domain). Do not edit.\nexport default ${JSON.stringify(data)};\n`;
  writeFileSync(join(OUT, name), body);
  console.log(name.padEnd(14), (body.length / 1024).toFixed(0).padStart(5), 'KB');
};

