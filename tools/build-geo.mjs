const riversWorld = rivers(0.2, null, 1).filter(r => r.i === 1 || /Nil|Euphrat|Tigris|Indus|Ganges|Jangtse|Gelber|Amazonas|Mississippi|Kongo|Sambesi|Niger|Mekong|Ob|Jenissei|Lena|Amur|Wolga|Donau|Rhein|Jordan/.test(r.n));

