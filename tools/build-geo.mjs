// ---------- lakes ----------
// The global set has the famous ones (Bodensee, Genfer See, Müritz); the Europe set adds many small ones.
const lakeName = f => { const n = f.properties.name_de || f.properties.name_en || f.properties.name || ''; if (n && f.properties.name_en && f.properties.name_en !== n) EN.lake[n] = f.properties.name_en; return n; };
const lakeOf = (f, tol, clip) => ({ n: lakeName(f), p: buildPolys(f.geometry, tol, clip, 0.0002) });
function lakes(tol, clip, glMaxRank) {
  const gl = lakesGl.features.filter(f => f.properties.scalerank <= glMaxRank);
  const names = new Set(gl.map(lakeName));
  const eu = clip ? lakesEu.features.filter(f => !names.has(lakeName(f))) : [];
  return [...gl, ...eu].map(f => lakeOf(f, tol, clip)).filter(l => l.p.length);
}
const lakesCentral = lakes(0.01, CENTRAL, 99);
const lakesEuropeLod = lakes(0.04, EUROPE, 4);
const lakesWorld = lakes(0.15, null, 1);

// ---------- rivers ----------
function rivers(tol, clip, maxImportance) {
  const out = new Map();
  const add = (props, geom, src) => {
    const name = riverName(props);
    if (!name) return;
    const en = props.name_en || props.name; if (en && en !== name) EN.river[name] ??= en;
    const imp = importance(props.scalerank);
    if (imp > maxImportance) return;
    const lines = geom.type === 'LineString' ? [geom.coordinates] : geom.coordinates;
    const key = name;
    const e = out.get(key) || { n: name, i: imp, l: [] };
    e.i = Math.min(e.i, imp);
    for (const line of lines) {
      for (const run of (clip ? clipLine(line, clip) : [line])) {
        const s = rdp(run, tol);
        if (s.length > 1) e.l.push(flat(s));
      }
    }
    if (e.l.length) out.set(key, e);
  };
  // Global centre-lines carry the big rivers; the Europe set adds the smaller named ones.
  for (const f of rGl.features) add(f.properties, f.geometry, 'g');
  const have = new Set(out.keys());
  for (const f of rEu.features) { const nm = riverName(f.properties); if (nm && !have.has(nm)) add(f.properties, f.geometry, 'e'); }
  return [...out.values()];
}
